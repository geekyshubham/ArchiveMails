import os
"""Extract locally available document text for archive search. Does not run macros or OCR."""
import json,zipfile,xml.etree.ElementTree as ET,collections,hashlib,logging
from pathlib import Path
from email import policy
from email.parser import BytesParser
from pypdf import PdfReader
logging.getLogger('pypdf').setLevel(logging.ERROR)
CODE_ROOT=Path(__file__).resolve().parents[1]
ROOT=Path(os.environ.get('MDUMP_WORK_ROOT',str(CODE_ROOT))).resolve();OUT=ROOT/'MailArchive';index=json.loads((OUT/'index.json').read_text());manifest=json.loads((OUT/'manifest.json').read_text())
files={}
for m in index:
 for a in m['attachments']:
  if a.get('path'):
   f=files.setdefault(a['path'],dict(a,mailIds=[]));f['mailIds'].append(m['id'])
for a in manifest['unlinkedFiles']:
 files.setdefault(a['path'],dict(a,name=Path(a['path']).name,mailIds=[]))
results=[]
for path,a in files.items():
 p=OUT/path;text='';status='unsupported';error=None;ext=p.suffix.lower()
 try:
  if ext=='.pdf':
   pdf=PdfReader(p);text='\n\n'.join(f'[Page {i+1}]\n'+page.extract_text() for i,page in enumerate(pdf.pages));status='indexed' if text.strip() and any(page.extract_text().strip() for page in pdf.pages) else 'no_text'
  elif ext in ['.docx','.pptx','.xlsx']:
   with zipfile.ZipFile(p) as z:
    names=[n for n in z.namelist() if (n.startswith('word/') and n.endswith('.xml') and any(s in n for s in ['document','header','footer','footnotes','endnotes'])) or (n.startswith('ppt/slides/slide') and n.endswith('.xml')) or (n.startswith('xl/') and n.endswith('.xml') and ('sharedStrings' in n or 'worksheets/sheet' in n))]
    chunks=[]
    for n in sorted(names):
     tree=ET.fromstring(z.read(n));texts=[e.text for e in tree.iter() if e.tag.rsplit('}',1)[-1] in ('t','v') and e.text]
     chunks.append(n+'\n'+' '.join(texts))
    text='\n\n'.join(chunks);status='indexed' if text.strip() else 'no_text'
  elif ext in ['.txt','.csv','.ics','.json','.xml','.html','.htm','.md']:
   text=p.read_text(encoding='utf-8',errors='replace');status='indexed'
  elif ext=='.eml':
   mail=BytesParser(policy=policy.default).parsebytes(p.read_bytes());text=str(mail.get('Subject',''))+'\n'+'\n'.join(part.get_content() for part in mail.walk() if part.get_content_type()=='text/plain');status='indexed'
 except Exception as e:status='extraction_failed';error=type(e).__name__
 results.append({'id':'file:'+hashlib.sha256(path.encode()).hexdigest()[:20],'path':path,'name':a['name'],'mailIds':a['mailIds'],'status':status,'text':text,'error':error})
texts={r['path']:r['text'] for r in results if r['text']}
for m in index:
 # Original index is regenerated by export_mail before this script runs.
 m['searchText']+='\n'+'\n'.join(texts.get(a['path'],'').casefold() for a in m['attachments'] if a.get('path'))
(OUT/'index.json').write_text(json.dumps(index,ensure_ascii=False));(OUT/'data/attachment-text.json').write_text(json.dumps(results,ensure_ascii=False))
manifest['attachmentText']=dict(collections.Counter(r['status'] for r in results));manifest['limitations'].append('AI searches recovered message text, calendar records and extracted document text. Images, scans without text, encrypted files and audio/video are not transcribed.')
manifest['dataFiles']=[x for x in manifest['dataFiles'] if x['name']!='attachment-text']+[{'name':'attachment-text','path':'data/attachment-text.json','records':len(results)}]
(OUT/'manifest.json').write_text(json.dumps(manifest,indent=2,ensure_ascii=False));print(manifest['attachmentText'])
